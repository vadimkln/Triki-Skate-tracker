const DICT = { uk, en, pl };
export const LANGS = ['uk', 'en', 'pl'];
const LOCALE = { uk: 'uk-UA', en: 'en-GB', pl: 'pl-PL' };

function detectLang() {
  if (S.lang && DICT[S.lang]) return S.lang;
  const list = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || 'en'];
  for (const l of list) { const c = String(l).slice(0, 2).toLowerCase(); if (DICT[c]) return c; }
  return 'en';
}

export let lang = detectLang();
export const locale = () => LOCALE[lang];

export function t(key, p) {
  let s = DICT[lang][key];
  if (s == null) s = en[key];
  if (s == null) return key;
  return p ? s.replace(/\{(\w+)\}/g, (m, k) => (p[k] != null ? p[k] : m)) : s;
}

// Числа з комою для української й польської
export function num(v, d = 0) {
  let x = +Number(v).toFixed(d);
  if (!x) x = 0;                       // без «-0»
  return x.toLocaleString(locale(), { minimumFractionDigits: d, maximumFractionDigits: d });
}
export const fmtTime = ms => new Date(ms).toLocaleTimeString(locale(), { hour: '2-digit', minute: '2-digit', hour12: false });
export const fmtDate = ms => new Date(ms).toLocaleDateString(locale());

// Назви трюків англійські в усіх мовах (так кажуть скейтери), перекладаємо лише «Інше»
export const trickName = n => (n === 'Other' || n === 'Інше' ? t('trick.Other') : n);

// Позначки трюку зберігаються як {k, d}; старі сесії мають готовий текст
export function flagText(f) {
  if (typeof f === 'string') return f;
  return t('flag.' + f.k, { d: f.d != null ? num(f.d) : '' });
}
export function reasonText(r) {
  if (!r) return '';
  return uk['reason.' + r] ? t('reason.' + r) : r;
}

export function applyStatic(root = document) {
  document.documentElement.lang = lang;
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
}

export function setLang(l) {
  if (!DICT[l]) return;
  lang = l; S.lang = l; saveSettings();
  applyStatic();
  bus.emit('lang');
}
